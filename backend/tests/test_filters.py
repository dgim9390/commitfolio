import pytest

SAMPLE_PATCH = """\
diff --git a/src/app.ts b/src/app.ts
index 1111111..2222222 100644
--- a/src/app.ts
+++ b/src/app.ts
@@ -1,3 +1,3 @@
 const a = 1;
--- this line starts with dashes
+const b = 2;
diff --git a/new file.py b/new file.py
new file mode 100644
index 0000000..3333333
--- /dev/null
+++ b/new file.py
@@ -0,0 +1,2 @@
+print("hi")
+print("bye")
diff --git a/old.txt b/renamed.txt
similarity index 90%
rename from old.txt
rename to renamed.txt
diff --git a/logo.png b/logo.png
new file mode 100644
index 0000000..4444444
Binary files /dev/null and b/logo.png differ
diff --git a/gone.js b/gone.js
deleted file mode 100644
index 5555555..0000000
--- a/gone.js
+++ /dev/null
@@ -1 +0,0 @@
-x()
"""


def test_parse_patch():
    files = {f.path: f for f in parse_patch(SAMPLE_PATCH)}
    assert set(files) == {"src/app.ts", "new file.py", "renamed.txt", "logo.png", "gone.js"}

    app = files["src/app.ts"]
    # 헝크 안의 "--- this line..."은 헤더가 아니라 삭제된 줄이다
    assert (app.status, app.additions, app.deletions) == ("modified", 1, 1)

    assert files["new file.py"].status == "added"
    assert files["new file.py"].additions == 2
    assert files["renamed.txt"].status == "renamed"
    assert files["renamed.txt"].old_path == "old.txt"
    assert files["renamed.txt"].patch is None
    assert files["logo.png"].is_binary
    assert files["gone.js"].status == "deleted"
    assert files["gone.js"].deletions == 1


@pytest.mark.parametrize(
    ("path", "expected"),
    [
        ("package-lock.json", "lock"),
        ("web/yarn.lock", "lock"),
        ("dist/index.js", "build"),
        ("a/node_modules/x/index.js", "build"),
        ("desktop/build/make-icon.py", None),  # Electron 리소스 폴더의 직접 작성한 스크립트
        ("static/app.min.js", "minified"),
        ("img/logo.PNG", "binary"),
        ("proto/user_pb2.py", "generated"),
        ("src/main.py", None),
    ],
)
def test_exclusion_by_path(path, expected):
    assert exclusion_reason(FileChange(path=path, patch="@@ -1 +1 @@\n+x"), max_lines=3000) == expected


def test_exclusion_by_content():
    generated = FileChange(path="api/client.ts", patch="@@ -0,0 +1 @@\n+// Code generated by openapi. DO NOT EDIT.")
    assert exclusion_reason(generated, 3000) == "generated"

    bundle = FileChange(path="build/app.js", patch="@@ -0,0 +1 @@\n+" + "a" * 2000)
    assert exclusion_reason(bundle, 3000) == "minified"

    huge = FileChange(path="data/seed.ts", additions=5000, patch="@@ -0,0 +1 @@\n+x")
    assert exclusion_reason(huge, 3000) == "too_large"


def test_truncate_patch():
    patch = "\n".join(f"+line {i}" for i in range(100))
    out, cut = truncate_patch(patch, 50)
    assert cut
    assert out.endswith("줄 생략)")
    assert out.splitlines()[0] == "+line 0"

    same, cut = truncate_patch("short", 50)
    assert (same, cut) == ("short", False)


def test_allocate_budget():
    # 작은 파일은 다 받고, 남은 예산을 큰 파일들이 똑같이 나눈다
    assert allocate_budget([100, 5000, 5000], 3100) == [100, 1500, 1500]
    # 예산이 넉넉하면 모두 원래 크기 그대로
    assert allocate_budget([100, 200], 1000) == [100, 200]
    assert allocate_budget([], 1000) == []


def _commit(files: list[FileChange]) -> Commit:
    return Commit(sha="a" * 40, url="", message="m", authored_at="2026-01-01T00:00:00Z", author_login="u", files=files)


def test_apply_filters_shares_budget():
    settings = Settings(max_patch_chars_per_file=1000, max_patch_chars_per_commit=1500)
    body = "\n".join(f"+{i:04}" for i in range(400))  # 약 2400자
    commit = _commit([FileChange(path=f"f{i}.py", patch=body) for i in range(3)] + [FileChange(path="yarn.lock", patch=body)])
    apply_filters([commit], settings)
    *sources, lock = commit.files
    # 예산 1500을 세 파일이 약 500씩 나눠 가진다 (앞 파일이 독차지하지 않음)
    for f in sources:
        assert f.truncated and f.patch is not None
        assert 400 < len(f.patch) < 560
    assert lock.excluded_reason == "lock" and lock.patch is None


def test_apply_filters_drops_tiny_share():
    settings = Settings(max_patch_chars_per_file=1000, max_patch_chars_per_commit=500)
    body = "\n".join(f"+{i:04}" for i in range(400))
    commit = _commit([FileChange(path=f"f{i}.py", patch=body) for i in range(4)])
    apply_filters([commit], settings)
    # 몫이 125자뿐이면 조각을 남기지 않고 파일 이름·줄 수만 남긴다
    assert all(f.patch is None and f.truncated for f in commit.files)


