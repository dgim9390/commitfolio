GENERATED_SUFFIXES = (
    "_pb2.py", "_pb2_grpc.py", ".pb.go", ".g.dart", ".freezed.dart",
    ".generated.ts", ".generated.js", ".d.ts.map",
)  # fmt: skip

# 파일 첫머리에 이런 문구가 있으면 자동 생성 파일로 본다
GENERATED_MARKERS = (
    "@generated", "do not edit", "auto-generated", "autogenerated",
    "automatically generated", "generated by",
)  # fmt: skip


def exclusion_reason(f: FileChange, max_lines: int) -> str | None:
    """파일을 제외해야 하면 이유 코드를, 분석 대상이면 None을 돌려준다."""
    p = PurePosixPath(f.path)
    name = p.name
    lower = name.lower()

    if name in LOCK_FILES:
        return "lock"
    if any(part in BUILD_DIRS for part in p.parts[:-1]):
        return "build"
    if lower.endswith(MINIFIED_SUFFIXES) or _looks_minified(f.patch):
        return "minified"
    if f.is_binary or p.suffix.lower() in BINARY_EXTS:
        return "binary"
    if lower.endswith(GENERATED_SUFFIXES) or _has_generated_marker(f.patch):
        return "generated"
    if f.lines_changed > max_lines:
        return "too_large"
    return None


def _looks_minified(patch: str | None) -> bool:
    """사람이 쓴 코드에는 거의 없는 아주 긴 줄이 있으면 번들/압축 결과물로 본다."""
    if not patch:
        return False
    return any(len(line) > 1000 for line in patch.splitlines())


def _has_generated_marker(patch: str | None) -> bool:
    if not patch:
        return False
    head = "\n".join(patch.splitlines()[:15]).lower()
    return any(marker in head for marker in GENERATED_MARKERS)


def truncate_patch(patch: str, max_chars: int) -> tuple[str, bool]:
    """줄 단위로 max_chars 이내까지만 남긴다. (잘린 결과, 잘렸는지 여부)"""
    if len(patch) <= max_chars:
        return patch, False
    cut = patch.rfind("\n", 0, max_chars)
    if cut <= 0:
        cut = max_chars
    kept, rest = patch[:cut], patch[cut:]
    omitted = rest.count("\n") + (0 if rest.endswith("\n") else 1)
    return f"{kept}\n... (이하 {omitted}줄 생략)", True


def allocate_budget(sizes: list[int], budget: int) -> list[int]:
    """커밋 예산을 파일들에 공평하게 나눈다 (water-filling).

    작은 파일부터 보면서 '남은 예산 / 남은 파일 수'만큼을 몫으로 준다.
    필요한 양이 몫보다 작은 파일은 필요한 만큼만 쓰고, 남은 예산은 뒤의 큰 파일들이 나눠 가진다.
    → 앞쪽 파일이 예산을 다 써서 뒤쪽 파일 diff가 통째로 사라지는 일이 없다.
    """
    alloc = [0] * len(sizes)
    remaining = budget
    order = sorted(range(len(sizes)), key=lambda i: sizes[i])
    for k, i in enumerate(order):
        share = remaining // (len(order) - k)
        alloc[i] = min(sizes[i], share)
        remaining -= alloc[i]
    return alloc


# 이보다 적게 배정되면 diff 조각이 의미가 없으므로 파일 이름·줄 수만 남긴다
MIN_USEFUL_PATCH_CHARS = 300


def apply_filters(commits: list[Commit], settings: Settings) -> None:
    """커밋 목록의 파일들에 제외 표시를 하고 diff를 자른다. (제자리 수정)"""
    for commit in commits:
        kept: list[FileChange] = []
        for f in commit.files:
            reason = exclusion_reason(f, settings.max_file_lines_changed)
            if reason:
                f.excluded_reason = reason
                f.patch = None
            elif f.patch:
                kept.append(f)

        sizes = [min(len(f.patch), settings.max_patch_chars_per_file) for f in kept]
        for f, limit in zip(kept, allocate_budget(sizes, settings.max_patch_chars_per_commit)):
            if limit < min(len(f.patch), MIN_USEFUL_PATCH_CHARS):
                f.patch, f.truncated = None, True
            else:
                f.patch, f.truncated = truncate_patch(f.patch, limit)


