# 제외 이유 코드 → 화면 표시용 이름
REASON_LABELS = {
    "lock": "lock 파일",
    "build": "빌드 산출물",
    "minified": "압축/소스맵",
    "binary": "바이너리·에셋",
    "generated": "자동 생성",
    "too_large": "변경량 과다",
}

LOCK_FILES = {
    "package-lock.json", "yarn.lock", "pnpm-lock.yaml", "bun.lockb", "bun.lock",
    "poetry.lock", "uv.lock", "Pipfile.lock", "Cargo.lock", "Gemfile.lock",
    "composer.lock", "go.sum", "flake.lock", "Podfile.lock", "pubspec.lock",
}  # fmt: skip

# 거의 항상 산출물만 들어가는 폴더.
# "build", "out", "target"은 일부러 뺐다: Electron의 build/처럼 직접 작성한 스크립트·리소스를
# 두는 경우가 흔해서, 폴더 이름만으로 제외하면 실제 작업이 빠진다.
# 그런 폴더에 커밋된 번들 파일은 아래 '줄이 비정상적으로 긴 파일' 규칙으로 걸러진다.
BUILD_DIRS = {
    "dist", ".next", ".nuxt", ".svelte-kit", ".output", "node_modules",
    "coverage", "__pycache__", ".venv", "venv", "vendor", ".turbo",
}  # fmt: skip

MINIFIED_SUFFIXES = (".min.js", ".min.css", ".map", ".bundle.js", ".chunk.js")

