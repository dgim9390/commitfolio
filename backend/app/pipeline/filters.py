def user_languages(commits: list[Commit]) -> dict[str, int]:
    """분석 대상 파일의 변경 줄 수를 언어별로 합산 (많은 순)."""
    totals: dict[str, int] = {}
    for c in commits:
        for f in c.included_files:
            p = PurePosixPath(f.path)
            lang = "Dockerfile" if p.name == "Dockerfile" else EXT_LANGUAGES.get(p.suffix.lower())
            if lang:
                totals[lang] = totals.get(lang, 0) + f.lines_changed
    return dict(sorted(totals.items(), key=lambda kv: -kv[1]))
