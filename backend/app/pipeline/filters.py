"""분석 대상이 아닌 파일 제외 + diff 길이 제한.

제외해도 파일 이름과 변경 줄 수는 남겨 둔다. LLM이 "의존성을 추가했다",
"이미지 에셋을 넣었다" 같은 맥락은 diff 없이도 알 수 있게 하기 위해서다.
"""

